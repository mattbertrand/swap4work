const warnPrefix = "[i18n] Missing translation for key:";

// Translate a key with optional {variable} interpolation.
export function translate(lang, key, vars) {
  const es = translations.es;
  const en = translations.en;
  let text = es[key] ?? en[key];
  if (text == null) {
    if (import.meta.env.DEV) console.warn(`${warnPrefix} ${key}`);
    return key;
  }
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

// Plural-aware translation: picks `${key}_one` or `${key}_other`.
export function translatePlural(lang, key, count, vars = {}) {
  const form = Number(count) === 1 ? "one" : "other";
  return translate(lang, `${key}_${form}`, { ...vars, count });
}